"""Generates docs/ML_REPORT.md from the out-of-sample predictions in the demo trading log.

Run (from backend/):  python -m ml.demo_trading_logger.accuracy_report
Every number in the report is computed here from stored walk-forward predictions; nothing is typed by hand.
"""

from __future__ import annotations

import json
import sqlite3
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from ml.calibration.strength import MIN_TIER_N, NO_EDGE, TIER_LEVELS, TIER_ORDER
from ml.demo_trading_logger import store
from ml.evaluation.metrics import MAX_NAIVE_RATE, summarize
from ml.settings import get_settings
from ml.training.model import git_commit


def _pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{x * 100:.{digits}f}%"


def _ci(stats: dict[str, Any]) -> str:
    if not stats["n"]:
        return "n/a"
    lo, hi = stats["ci95"]
    return f"{_pct(stats['rate'])} ({lo * 100:.1f}-{hi * 100:.1f})"


def _date(ts: int) -> str:
    return datetime.fromtimestamp(ts, tz=UTC).strftime("%Y-%m-%d")


def _title(run: dict[str, Any]) -> str:
    horizon = "next candle" if run["horizon"] == 1 else f"{run['horizon']} candles ahead"
    return f"{run['symbol']} {run['interval']}, {horizon}"


def build_report(conn: sqlite3.Connection, generated_at: datetime | None = None) -> str:
    generated_at = generated_at or datetime.now(UTC)
    runs = store.latest_runs(conn).to_dict("records")
    sections, summary_rows = [], []
    for run in runs:
        pred = store.load_predictions(conn, run["run_id"])
        m = summarize(pred)
        data, cfg, cuts = json.loads(run["data_json"]), json.loads(run["config_json"]), json.loads(run["cuts_json"])
        usable = m["usability"]["usable"]
        earned = [t for t, _ in TIER_LEVELS if cuts.get(t) is not None] if usable else []
        acc, base, naive = m["accuracy"], m["baseline_accuracy"], m["naive_baseline"]
        best = max(base["rate"], naive["rate"])
        beats = "yes" if usable else "**no**"
        summary_rows.append(
            f"| {_title(run)} | {_date(m['period']['first_time'])} to {_date(m['period']['last_time'])} "
            f"| {m['n_oos']:,} | {_ci(acc)} | {_pct(base['rate'])} | {_pct(naive['rate'])} ({naive['rule']}) "
            f"| {(acc['rate'] - best) * 100:+.1f} pp | {beats} | {_pct(data['flat_rate'])} "
            f"| {m['ece_raw'] * 100:.1f} -> {m['ece_cal'] * 100:.1f} pp | {', '.join(earned) or 'none'} |")
        sections.append(_model_section(run, m, data, cfg, cuts))

    header = f"""# Zentrix ML report: out-of-sample results

_Generated by `python -m ml.demo_trading_logger.accuracy_report` on {generated_at:%Y-%m-%d %H:%M} UTC
(code `{git_commit() or 'unknown'}`) from {len(runs)} walk-forward runs in the demo trading log.
Do not edit by hand; rerun the pipeline (`python -m ml.training.pipeline`) and this script._

**Not financial advice.** These are historical, out-of-sample measurements of research models. They do not
guarantee future results and must not be presented as a promise of accuracy or profit. Numbers shown to users
later must come from the live track record in the database, not from this file.

## Method

- **Walk-forward, out-of-sample only.** Rows are split in time: an initial training span, then
  {cfg_blocks(runs)} test blocks. Each block is predicted by a model trained only on earlier rows; training
  rows whose label was not yet known at the block's first decision time are purged.
- **Closed candles only.** Features (including the higher-timeframe trend) use candles that had closed by
  the decision time. Signals are computed on the last closed candle.
- **Calibration (Platt).** Block k is calibrated with a calibrator fitted on the raw predictions of blocks
  before k. Headline numbers use blocks 2 and later (block 1 only seeds the calibrator).
- **Strength tiers.** A tier is earned when signals at or above a confidence cut (grid 0.50-0.80) have a
  lower confidence bound on hit rate (Wilson, Bonferroni-adjusted over the grid) of at least:
  {', '.join(f'{t} {lvl:.0%}' for t, lvl in TIER_LEVELS[:-1])}, Weak > 50% (min {MIN_TIER_N} signals).
  Cuts for block k are chosen on earlier blocks; tier hit rates use blocks 3+. Everything else is
  "{NO_EDGE}" (no demonstrated edge).
- **Label (open to open).** A signal is made at the close of candle t. Entry = open of candle t+1 (the first
  price a trader can act on); exit = open of candle t+h+1 (the first price after candle t+h closes). Up = exit
  above entry. Flat outcomes are excluded from training and accuracy; their rate is listed.
- **Why not close to close (the original label).** In the Twelve Data forex/gold feed a candle's open sits
  systematically below the previous close and candle bodies are up far more often than down (a clean feed
  shows ~50%): open and close behave like different sides of the bid/ask spread. Close-to-close labels then
  carry spread noise that a trivial rule predicts, and mixing open and close builds in a fake upward drift.
  Comparing open with open cancels the constant offset. Two **feed checks** per model show the effect
  (both ~50% on a clean feed). Where they are far from 50%, also read the naive baseline below.
- **Baselines.** (1) Majority: always predict the training data's majority direction. (2) Naive: the better
  (chosen after the fact) of "repeat the last candle's body direction" and "reverse it", which captures most
  feed-noise effects. "Edge" is accuracy minus the better baseline; "Beats baselines" means the 95% interval
  lies entirely above it. A model that does not beat the naive rule has shown no usable edge.
- **Usable for signals.** Yes only if the 95% interval clears both baselines and the naive rule scores below
  {MAX_NAIVE_RATE:.0%} (above that, the label is dominated by feed structure). Models that are not usable serve
  every signal as "{NO_EDGE}", whatever tiers the walk-forward found.
- **Market hours.** Forex and gold use candles from the trading week only (Sun 17:00 to Fri 17:00 New York).
  The feed also returns closed-market candles (~25%); they are dropped in training and live inference.
- **Accuracy is not profitability.** Hit rate ignores move size, spread, commission and slippage. No trading
  returns are claimed here.
- ECE = expected calibration error of stated confidence (lower is better). Intervals are 95% Wilson intervals.
- Earlier figures from the removed `historical_simulator.py` (~60% overall, 83-89% "high confidence") were
  measured on the model's own training data and are invalid.

## Summary

| Model | OOS period (UTC) | OOS signals | Accuracy (95% CI) | Majority | Naive last-candle rule | Edge vs better baseline | Usable for signals | Flat | ECE raw -> calibrated | Tiers earned |
|---|---|---|---|---|---|---|---|---|---|---|
"""
    return header + "\n".join(summary_rows) + "\n\n## Per model\n\n" + "\n".join(sections)


def cfg_blocks(runs: list[dict[str, Any]]) -> str:
    blocks = sorted({json.loads(r["config_json"])["n_blocks"] for r in runs})
    return "/".join(map(str, blocks)) or "K"


def _model_section(run: dict[str, Any], m: dict[str, Any], data: dict[str, Any], cfg: dict[str, Any],
                   cuts: dict[str, float | None]) -> str:
    rel = "\n".join(
        f"| {r['bin'][0]:.2f}-{r['bin'][1]:.2f} | {r['n']:,} | {_pct(r['mean_confidence'])} | {_ci(r)} |"
        for r in m["reliability"] if r["n"])
    tiers = "\n".join(
        f"| {t} | {'-' if t == NO_EDGE else ('not earned' if cuts.get(t) is None else f'{cuts[t]:.3f}')} "
        f"| {m['tiers'][t]['n']:,} | {_pct(m['tiers'][t]['share'])} | {_ci(m['tiers'][t])} |"
        for t in TIER_ORDER)
    blocks = ", ".join(f"B{b['block']} {_pct(b['rate'])}" for b in m["per_block"])
    usability = ("yes" if m["usability"]["usable"]
                 else "**no** - " + "; ".join(m["usability"]["reasons"]) + '. Tiers below are not served.')
    return f"""### {_title(run)}

Usable for signals: {usability}

Data: {data['n_candles']:,} closed candles, {data['n_rows']:,} labelled rows, flat outcomes {_pct(data['flat_rate'])},
label `{data.get('label_mode', 'close_to_close')}`. Feed checks (~50% on a clean feed): up bodies
{_pct(data.get('body_up_share'))}, next open jumps against the body {_pct(data.get('next_open_reversal_rate'))}.
Calibrated accuracy {_ci(m['accuracy'])} on {m['n_oos']:,} signals vs majority baseline
{_pct(m['baseline_accuracy']['rate'])} (up-rate {_pct(m['up_rate'])}) and naive rule
{_pct(m['naive_baseline']['rate'])} ({m['naive_baseline']['rule']}); raw-model accuracy
{_pct(m['raw_accuracy']['rate'])}. Brier {m['brier']:.4f} (raw {m['brier_raw']:.4f}), log loss {m['log_loss']:.4f}.
Per block: {blocks}.

Reliability (calibrated, stated confidence vs observed hit rate):

| Stated confidence | Signals | Mean stated | Observed (95% CI) |
|---|---|---|---|
{rel}

Strength tiers (cut = production confidence threshold; hit rates from blocks 3+):

| Tier | Cut | Signals | Share | Hit rate (95% CI) |
|---|---|---|---|---|
{tiers}
"""


def generate_report(db_path: Path | None = None, out_path: Path | None = None) -> Path:
    out_path = out_path or get_settings().ml_report_path
    conn = store.connect(db_path)
    try:
        text = build_report(conn)
    finally:
        conn.close()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding="utf-8", newline="\n")
    return out_path


if __name__ == "__main__":
    print("Wrote", generate_report())
